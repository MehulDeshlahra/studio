"""knowledge/STATE.md: the server's own, always-current picture of Studio (owner 18 Nov: a session started from a
hand-written RESUME.md with stale items). Written by the healer every 15 min; committed by sync.py.
A new Kiro session reads THIS first; RESUME.md keeps only decisions and history.
  python engine/state.py   (prints the file too)"""
import glob, json, os, re, subprocess, sys, time
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from core import ROOT, OUT, load

PATH = os.path.join(ROOT, "knowledge", "STATE.md")


def sh(cmd, timeout=30):
    try:
        return subprocess.run(cmd, shell=True, capture_output=True, text=True, timeout=timeout).stdout.strip()
    except Exception:
        return ""


def _mem():
    m = {l.split(":")[0]: int(l.split()[1]) // 1024 for l in open("/proc/meminfo") if l.split(":")[0] in ("MemAvailable", "MemTotal", "SwapFree", "SwapTotal")}
    return m


def write():
    L = [f"# STATE (written by the server, {time.strftime('%d %b %Y %H:%M')} IST)", "",
         "Auto-generated by engine/state.py every 15 min. Facts only, read from the live server. Do not edit by hand.", ""]
    m = _mem()
    du = sh("df -h / | tail -1 | awk '{print $5\" used, \"$4\" free\"}'")
    load_ = " ".join(open("/proc/loadavg").read().split()[:3])
    low = " (LOW: manual jobs must wait, rule 2.5 GB)" if m.get("MemAvailable", 0) < 2500 else ""
    L += ["## Server", f"- Memory: {m.get('MemAvailable', 0)} MB free of {m.get('MemTotal', 0)} MB{low}; disk {du}; load {load_}",
          f"- Up since: {sh('uptime -s')}"]
    run = sh("systemctl list-units --state=active,activating --no-legend --plain 'studio-job-*.service' 'studio-make.service' 'studio-prep.service' | awk '{print $1}'")
    L.append("- Running now: " + (", ".join(run.split()) if run else "nothing (lanes idle)"))
    act = [l for l in open(os.path.join(OUT, "engine.log"), encoding="utf-8", errors="ignore").readlines()[-300:]
           if re.search(r"\bjob \w+ \S+ |render lane|prep lane", l)][-3:]
    L += [f"  - {a.strip()[:170]}" for a in act]
    failed = sh("systemctl list-units --failed --no-legend --plain 'studio*' | awk '{print $1}'")
    L.append("- Failed units: " + (failed.replace("\n", ", ") if failed else "none"))
    L.append("")
    # videos
    L.append("## Videos (channels/*/done.json)")
    for cid in ("tech", "katha", "raaz"):
        done = load(os.path.join(ROOT, "channels", cid, "done.json"), []) or []
        c = {}
        for d in done:
            c[d.get("status")] = c.get(d.get("status"), 0) + 1
        L.append(f"- {cid}: " + ", ".join(f"{k} {v}" for k, v in sorted(c.items(), key=lambda x: str(x[0]))))
        for d in done:
            if d.get("status") == "held":
                L.append(f"  - HELD {d['job']}: {'; '.join(map(str, d.get('review') or []))[:200]}")
    # 18 Nov focus week: the quality number to push up - share of videos that pass the pre-render check on the FIRST try
    try:
        first, held = {}, set()
        for ln in open(os.path.join(OUT, "engine.log"), encoding="utf-8", errors="ignore").readlines()[-30000:]:
            if ln[:10] < time.strftime("%Y-%m-%d", time.localtime(time.time() - 86400)):
                continue
            m = re.match(r"\S+ \S+ preflight (\S+) (OK|\d+ scene)", ln)
            if m and m.group(1) not in first:
                first[m.group(1)] = m.group(2) == "OK"
            m = re.search(r"held BEFORE render \(no render time spent\) \S+ (\S+)", ln)
            if m:
                held.add(m.group(1))
        if first:
            L.append(f"- Last 24 h: {sum(first.values())} of {len(first)} videos passed the pre-render check first time "
                     f"({100 * sum(first.values()) // len(first)}%); {len(held)} held before render after repairs")
    except Exception:
        pass
    L.append("")
    # healer
    hs = load(os.path.join(OUT, "healer.json"), {}) or {}
    items = hs.get("items", {})
    by = {}
    for k, it in items.items():
        by.setdefault(it.get("state") or "working", []).append((k, it))
    L.append("## Healer (engine/healer.py)")
    for st in ("open", "working", "parked", "fixed"):
        rows = by.get(st, [])
        if not rows:
            continue
        L.append(f"- {st}: {len(rows)}")
        for k, it in rows[-6:]:
            last = (it.get("steps") or [{}])[-1]
            L.append(f"  - {k}: {(it.get('why') or last.get('result') or last.get('step') or it.get('what') or '')[:150]}")
    L += [f"- {x['t']} {x['what'][:170]}" for x in hs.get("log", [])[-8:]]
    fx = load(os.path.join(ROOT, "knowledge", "fixes.json"), []) or []
    L.append(f"- Known fixes learned: {len(fx)}" + ("".join(f"\n  - {f['fix']} x{f['n']}: {f['example'][:120]}" for f in fx[-5:])))
    L.append("")
    # models
    pr = load(os.path.join(OUT, "omni-probe.json"), {}) or {}
    res = pr.get("results", {})
    L.append("## Models (engine/omnimap.py, OmniRoute)")
    if res:
        okk = [k for k, r in res.items() if r.get("ok")]
        L.append(f"- Probe {pr.get('t')}: {len(okk)} of {len(res)} models answered correctly")
        prov = {}
        for k, r in res.items():
            p = k.split(":", 1)[1].split("/")[0]
            prov.setdefault(p, [0, 0]); prov[p][1] += 1; prov[p][0] += 1 if r.get("ok") else 0
        L.append("- By provider: " + ", ".join(f"{p} {a}/{b}" for p, (a, b) in sorted(prov.items())))
        for h in pr.get("healed", []):
            L.append(f"- Re-opened: {h}")
    try:
        import tts
        gem = ["gemini-3.8-flash", "gemini-3.5-flash-lite"] + tts.MODELS
        gone = [g for g in gem if g not in tts.usable(gem)]
        if gone:
            L.append("- Studio's own Gemini keys are out today for: " + ", ".join(gone) + " (text and vision go to OmniRoute)")
    except Exception:
        pass
    L.append("")
    # doctor + owner
    unk = load(os.path.join(OUT, "doctor-unknown.json"), []) or []
    L.append("## Doctor notes (last 5; the healer works through these)")
    L += [f"- {u.get('t')} {u.get('what', '')[:90]}: {u.get('detail', '')[:110]}" for u in unk[-5:]] or ["- none"]
    ot = load(os.path.join(OUT, "owner-tasks.json"), []) or []
    L.append("")
    L.append("## Needs the owner")
    rows = ot if isinstance(ot, list) else ot.get("tasks", []) if isinstance(ot, dict) else []
    L += [f"- {r.get('title') or r.get('what') or r.get('text')}: {r.get('why', '')}"[:200] for r in rows[-6:]
          if isinstance(r, dict) and not r.get("done")] or ["- nothing"]
    txt = "\n".join(L) + "\n"
    tmp = PATH + ".tmp"
    open(tmp, "w", encoding="utf-8").write(txt)
    os.replace(tmp, PATH)
    return txt


if __name__ == "__main__":
    print(write())
